function evaluateSuccess(){
  let success = car.isOnBoatRamp() && trailer.isInTargetWater();
  
  if(success) {
    showEndScreen(imgSuccess);
    return;
  }

  let isInTheDrink = car.isInWater() || trailer.isInWater() || car.isInTargetWater();
  if(isInTheDrink){
    showEndScreen(imgInTheDrink);
    return;
  }
}

    
function showEndScreen(img){
  image(img, width/2, height/2, height * img.width / img.height, height)
}


// Fixed handleKeyPresses function
function handleKeyPresses(){
  car.turningDir = 0;
  car.isAccelerating = false;

  // Forward
  if(keyIsDown(UP_ARROW)){
    car.isAccelerating = true;
    car.isDrivingForward = true;
  }

  // Backward
  if(keyIsDown(DOWN_ARROW)){
    car.isDrivingForward = false;
    car.isAccelerating = true;
  }

  // user presses forward and back at once?? 😅
  if(keyIsDown(UP_ARROW) && keyIsDown(DOWN_ARROW)){
    car.isDrivingForward = true;
    car.isAccelerating = false;
  }

  // Turn left
  if(keyIsDown(LEFT_ARROW)) car.turningDir = -1;
  // Turn Right
  if(keyIsDown(RIGHT_ARROW)) car.turningDir = 1;
  // Try to turn both directions at once 😅
  if(keyIsDown(LEFT_ARROW) && keyIsDown(RIGHT_ARROW)) car.turningDir = 0;
}

function drawMap(){
  // water
  let waterStart = 0.75;
  fill("#38afcd");
  rect(width/2, waterStart * height + (1 - waterStart) * height/2 , width, (1 - waterStart) * height);
  
  // ramp
  fill("#3b4747")
  rect(width/2, waterStart * height, width/5, waterStart * height / 3);

}