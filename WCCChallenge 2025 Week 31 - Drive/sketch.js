// --- Setup Function ---
function setup() {
    // Set canvas size
    createCanvas(windowWidth, windowHeight);
    imageMode(CENTER);
    rectMode(CENTER);

    // Define hitboxes for map elements
    hitBoatRamp = {
        x: width/2,
        y: 0.75 * height,
        w: width/5,
        h: 0.75 * height / 3
    };

    hitWater = {
        x: width/2,
        y: 0.75 * height + (1 - 0.75) * height/2,
        w: width,
        h: (1 - 0.75) * height
    };

    hitTargetWater = {
        x: width/2,
        y: 0.75 * height + (1 - 0.75) * height/2,
        w: width/5, // Same width as ramp for alignment
        h: (1 - 0.75) * height
};

    vehicleLength = min(width, height)/15;

    JACKKNIFE_ANGLE_THRESHOLD = PI * 0.75; // 135 degrees

    // Initial position of car (center of canvas)
    car = new DrivingBiz(width/2, height/2, vehicleLength, 2*vehicleLength, imgCar, false, 0, 100)
    let hitchPoint = car.calculateHitchPoint();

    // Set trailer's initial position so its hitch point aligns with car's hitch point
    trailer = new DrivingBiz(hitchPoint.x, hitchPoint.y, vehicleLength, 2*vehicleLength, imgTrailer, true, 0.98, 100)
    trailer.calculateHitchPoint();
    trailer.angle = car.angle; // Trailer starts aligned with the car

    
}



